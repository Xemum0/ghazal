// ImageCarousel (direction section 5): photographs that carry the screen.
//   hero   full-bleed, uncropped by shape, 440 high, starting under the status bar; hairline progress with a bead and a counter
//          ("3 of 12", canvas text) on the bottom scrim; the transparent TopBar overlays it. Tap opens the fullscreen viewer.
//   tour   16:10 pages with radius 12 and a peek of the next (the hall tour); width by the pager formula.
// Images reveal once over a static ink-100 placeholder (480 ms opacity + 3.5% settle, no shimmer). Fit is always cover, no filters.
import { useCallback, useLayoutEffect, useRef, useState } from 'react'
import { flat } from '@gz/tokens'
import { useT } from '../../i18n'
import { useDevice } from '../../shell/device/context'
import { cx } from '../core/cx'
import { Pager, PagerProgress, pagerItemWidth } from './Pager'
import { rectOf, type Rect } from './flip'
import './carousel.css'

export type CarouselImage = {
  /** URL as served; fixture photos are `/images/<file>` (see `imageSrc`). */
  src: string
  alt: string
}

/** Public URL of a curated photograph (`ImageRef.file` is relative to design/public/images). */
export const imageSrc = (file: string): string => `/images/${file}`

/** Widths generated by `design/scripts/images.mjs` into `/images/_v/<w>/<file>` (ADR 0024 D8: production variant sizes). */
const VARIANT_WIDTHS = [480, 800, 1200]
const IMAGES = '/images/'

/** `srcset` of a curated photograph from the variant convention; undefined for any other source (a data URL, a remote image). */
const srcSetOf = (src: string): string | undefined =>
  src.startsWith(IMAGES) && !src.startsWith(`${IMAGES}_v/`) ? VARIANT_WIDTHS.map(w => `${IMAGES}_v/${w}/${src.slice(IMAGES.length)} ${w}w`).join(', ') : undefined

/**
 * A photograph with the ink-100 placeholder and the once-only reveal. It serves the 480 / 800 / 1200 px variants (`sizes` is the slot's
 * width in CSS px, default one full phone column), decodes off the main thread and loads lazily unless it is the first thing on the
 * screen (`priority`). A variant that fails falls back to the original; an original that fails leaves the placeholder with the picture
 * still named for assistive technology.
 */
export function Photo({
  src, alt, className, fit = 'cover', sizes = '430px', priority = false,
}: { src: string; alt: string; className?: string; fit?: 'cover' | 'contain'; sizes?: string; priority?: boolean }) {
  const ref = useRef<HTMLImageElement>(null)
  const [loaded, setLoaded] = useState(false)
  const [failure, setFailure] = useState<'none' | 'variants' | 'all'>('none')
  const srcSet = failure === 'none' ? srcSetOf(src) : undefined
  // A cached image can finish before React attaches onLoad.
  useLayoutEffect(() => {
    setFailure('none')
    if (ref.current?.complete && ref.current.naturalWidth > 0) setLoaded(true)
  }, [src])
  if (failure === 'all') return <span className={cx('gz-photo gz-reveal-frame', className)} data-gz="Photo" data-missing="" role={alt ? 'img' : undefined} aria-label={alt || undefined} />
  return (
    <span className={cx('gz-photo gz-reveal-frame', className)} data-gz="Photo">
      <img
        ref={ref}
        className={cx('gz-photo__img', loaded && 'gz-reveal', fit === 'contain' && 'gz-photo__img--contain')}
        src={src}
        srcSet={srcSet}
        sizes={srcSet ? sizes : undefined}
        alt={alt}
        loading={priority ? 'eager' : 'lazy'}
        decoding="async"
        fetchPriority={priority ? 'high' : undefined}
        draggable={false}
        data-loaded={loaded || undefined}
        onLoad={() => setLoaded(true)}
        onError={() => setFailure(f => (f === 'none' && srcSetOf(src) ? 'variants' : 'all'))}
      />
    </span>
  )
}

export type ImageCarouselProps = {
  images: readonly CarouselImage[]
  variant?: 'hero' | 'tour'
  index?: number
  defaultIndex?: number
  onIndexChange?: (index: number) => void
  /** Tap on a photograph: the index and the rect of the tapped photo (the origin of the shared-element expansion). */
  onOpen?: (index: number, origin: Rect) => void
  /** Accessible name of the carousel ("Photos of Aurelia Gulf Hotel"). */
  label: string
  /** Counter and progress on the bottom scrim (hero). Default true. */
  showProgress?: boolean
}

const HERO_HEIGHT = flat['layout.hero.venue']

export function ImageCarousel({ images, variant = 'hero', index, defaultIndex = 0, onIndexChange, onOpen, label, showProgress = true }: ImageCarouselProps) {
  const t = useT('common')
  const { width } = useDevice()
  const [inner, setInner] = useState(defaultIndex)
  const current = index ?? inner
  const mode = variant === 'hero' ? 'full' : 'peek'
  const itemWidth = pagerItemWidth(width, mode)
  // tour: 16:10 by the formula, snapped to the 4-pt grid.
  const height = variant === 'hero' ? HERO_HEIGHT : Math.round((itemWidth * 10) / 16 / 4) * 4

  const change = useCallback(
    (i: number) => {
      if (index === undefined) setInner(i)
      onIndexChange?.(i)
    },
    [index, onIndexChange],
  )

  return (
    <div className={cx('gz-carousel', `gz-carousel--${variant}`)} data-gz="ImageCarousel" data-variant={variant}>
      <Pager mode={mode} index={current} onIndexChange={change} label={label}>
        {images.map((img, i) => (
          <button
            key={img.src}
            type="button"
            className="gz-reset gz-carousel__item"
            style={{ blockSize: height }}
            aria-label={img.alt}
            onClick={e => onOpen?.(i, rectOf(e.currentTarget.querySelector('img') ?? e.currentTarget))}
          >
            <Photo src={img.src} alt={img.alt} className="gz-carousel__photo" priority={i === current} />
          </button>
        ))}
      </Pager>
      {variant === 'hero' && showProgress && images.length > 1 ? (
        <>
          <span className="gz-carousel__scrim" aria-hidden="true" />
          <div className="gz-carousel__foot">
            <PagerProgress count={images.length} index={current} />
            <p className="gz-carousel__counter gz-t-caption" aria-label={t('commonA11yPhotoCounter', { current: current + 1, total: images.length })}>
              {t('commonCounter', { current: current + 1, total: images.length })}
            </p>
          </div>
        </>
      ) : null}
    </div>
  )
}
