/// Which illustrated error the screen state shows for a problem: no access, not found or a load failure.
GzErrorKind gzProblemKind(ApiProblem p) => switch (p.code) {
      ApiProblemCode.forbidden || ApiProblemCode.authRequired || ApiProblemCode.stepUpRequired => GzErrorKind.noAccess,
      ApiProblemCode.notFound || ApiProblemCode.voucherUnknown => GzErrorKind.notFound,
      ApiProblemCode.offline || ApiProblemCode.timeout => GzErrorKind.network,
      _ => GzErrorKind.load,
    };
