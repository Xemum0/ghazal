// `--nfkd` regenerates packages/ghazal_mock_api/lib/src/engine/nfkd_table.g.dart: the NFKD decompositions that normalizeSearch needs (Dart has no
// Unicode normaliser). Ranges: Latin, Arabic and its presentation forms, general punctuation and fullwidth forms.
if (process.argv.includes('--nfkd')) {
  const ranges = [[0xa0, 0x24f], [0x600, 0x6ff], [0x2000, 0x20cf], [0xfb00, 0xfb06], [0xfb50, 0xfdff], [0xfe70, 0xfeff], [0xff00, 0xffef]]
  const rows = []
  for (const [a, b] of ranges) for (let c = a; c <= b; c += 1) {
    const ch = String.fromCodePoint(c)
    const d = ch.normalize('NFKD')
    if (d !== ch) rows.push(`${c.toString(16)}:${[...d].map((x) => x.codePointAt(0).toString(16)).join('.')}`)
  }
  const out = `// GENERATED by tools/export-engine-cases.mjs --nfkd. Do not edit. NFKD decompositions (hex code point : hex code points joined by '.').
// ignore_for_file: lines_longer_than_80_chars
library;

const nfkdPairs = '${rows.join(',')}';
`
  fs.writeFileSync(path.join(root, 'packages/ghazal_mock_api/lib/src/engine/nfkd_table.g.dart'), out)
  console.log(`wrote nfkd_table.g.dart (${rows.length} decompositions)`)
  process.exit(0)
}

