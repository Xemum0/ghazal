// Proves the generated gen_l10n classes print the same strings as the web ICU runtime (ADR 0013, ADR 0036):
// formats a table of (key, args) pairs in both languages through intl-messageformat (packages/i18n createTranslator,
// the very code the prototype runs) and writes
//   packages/contracts/fixtures/message-cases.json   { bundles: { client|provider|ui: [{ id, call, lang, expect }] } }
//   <pkg>/test/l10n_calls.g.dart                     id of a call -> closure on AppL10n / GzL10n (Dart cannot call a
//                                                    getter by name, so the calls are generated)
// Coverage: every key with placeholders (plural keys with 0, 1, 2, 3, 11, 100; selects with every option; numbers),
// plus every 8th plain key and every rich-text key. Run: node tools/export-message-cases.mjs [--check]
import './lib/ts-register.mjs'
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { resolve } from 'node:path'
import { bundleMessages, bundles, dartTypes, root } from './lib/icu-arb.mjs'

const check = process.argv.includes('--check')
const { createTranslator } = await import(resolve(root, 'packages/i18n/src/index.ts'))

const PLURAL_COUNTS = [0, 1, 2, 3, 11, 100]
const NUMBERS = [0, 7, 1234, 12.5]
const dartLit = (v) => (typeof v === 'string' ? JSON.stringify(v).replace(/\$/g, '\\$') : String(v))

const out = {}
const dart = {}
const targets = { client: 'apps/client_app/test', provider: 'apps/provider_app/test', ui: 'packages/ghazal_ui/test' }

for (const [name, bundle] of Object.entries(bundles())) {
  const en = bundleMessages(bundle, 'en')
  const catalogs = { en, ar: bundleMessages(bundle, 'ar') }
  const translators = Object.fromEntries(['en', 'ar'].map((l) => [l, createTranslator({ lang: l, digitStyle: 'western', catalog: catalogs[l] })]))
  const cases = []
  const calls = []
  let plain = 0
  for (const key of Object.keys(en)) {
    const phs = dartTypes(en[key], key)
    const argSets = []
    if (phs.length === 0) {
      if (plain++ % 8 !== 0 && !/<[a-z]+>/.test(en[key])) continue
      argSets.push({})
    } else {
      const base = {}
      for (const p of phs) base[p.name] = p.kind === 'plural' ? 3 : p.kind === 'number' ? 7 : p.kind === 'select' ? p.options[0] : 'Sample'
      argSets.push({ ...base })
      for (const p of phs) {
        const values = p.kind === 'plural' ? PLURAL_COUNTS : p.kind === 'number' ? NUMBERS : p.kind === 'select' ? [...p.options.slice(1), 'zzz'] : []
        for (const v of values) if (v !== base[p.name]) argSets.push({ ...base, [p.name]: v })
      }
    }
    argSets.forEach((vals, i) => {
      const call = `${key}#${i}`
      const ordered = phs.map((p) => vals[p.name])
      calls.push(`  ${dartLit(call)}: (l) => l.${key}${phs.length ? `(${ordered.map(dartLit).join(', ')})` : ''},`)
      // Rich-text messages keep their tags literal in the ARB (GzRich splits them), so the web side re-emits each tag.
      const tags = [...new Set([...en[key].matchAll(/<([A-Za-z][A-Za-z0-9]*)>/g)].map((m) => m[1]))]
      const render = (lang) => {
        if (!tags.length) return translators[lang].t(key, vals)
        const withTags = { ...vals, ...Object.fromEntries(tags.map((t) => [t, (chunks) => `<${t}>${[].concat(chunks).join('')}</${t}>`])) }
        return translators[lang].rich(key, withTags).join('')
      }
      for (const lang of ['en', 'ar']) cases.push({ id: `${lang}.${call}`, call, lang, expect: render(lang) })
    })
  }
  out[name] = cases
  const cls = bundle.cls
  const importPath = name === 'ui' ? 'package:ghazal_ui/l10n/generated/gz_localizations.dart' : `package:${name === 'client' ? 'client_app' : 'provider_app'}/l10n/generated/app_localizations.dart`
  dart[name] = `// GENERATED by tools/export-message-cases.mjs. Do not edit.
// One closure per (key, args) call of the message-parity table; the expected strings live in
// packages/contracts/fixtures/message-cases.json.
import '${importPath}';

final Map<String, String Function(${cls})> kL10nCalls = <String, String Function(${cls})>{
${calls.join('\n')}
};
`
}

const doc = {
  _readme:
    'GENERATED by tools/export-message-cases.mjs from the web ICU runtime (intl-messageformat through @gz/i18n createTranslator). The Dart tests (apps/*/test/l10n_parity_test.dart, packages/ghazal_ui/test/l10n_parity_test.dart) load the generated AppL10n / GzL10n and must print the same strings. `call` names a closure in test/l10n_calls.g.dart.',
  counts: Object.fromEntries(Object.entries(out).map(([k, v]) => [k, v.length])),
  bundles: out,
}
const jsonText = `${JSON.stringify(doc)}\n`
const jsonPath = resolve(root, 'packages/contracts/fixtures/message-cases.json')
const files = [[jsonPath, jsonText], ...Object.entries(dart).map(([n, t]) => [resolve(root, targets[n], 'l10n_calls.g.dart'), t])]
if (check) {
  const stale = files.filter(([p, t]) => !existsSync(p) || readFileSync(p, 'utf8') !== t)
  if (stale.length) { console.error(`stale: ${stale.map(([p]) => p.replace(`${root}/`, '')).join(', ')}; run node tools/export-message-cases.mjs`); process.exit(1) }
  console.log('message cases are up to date')
} else {
  for (const [p, t] of files) writeFileSync(p, t)
  console.log(`wrote message cases: ${JSON.stringify(doc.counts)}`)
}
