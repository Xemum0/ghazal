// TypeScript + flat JSON generators (ADR 0023 D5 b). tokens.ts is `as const` and typed; tokens.flat.json feeds
// the spec / redline checkers (ADR 0024 D10): every token path resolves there.
import { cssName, rgba, HEADER } from './css.mjs'

/** Resolved token -> plain JS value (what code reads at runtime). */
export function plain(tok) {
  const { type, value } = tok
  switch (type) {
    case 'color': return rgba(value)
    case 'dimension': return value.value
    case 'duration': return value.value
    case 'shadow': return value.map(l => ({ color: rgba(l.color), x: l.offsetX.value, y: l.offsetY.value, blur: l.blur.value, spread: l.spread.value }))
    case 'gradient': return value.map(s => ({ color: rgba(s.color), position: s.position }))
    default: return value // number, string, fontFamily, cubicBezier, aspect, typography
  }
}

function nest(tokens) {
  const root = {}
  for (const t of tokens.values()) {
    const keys = t.path.split('.')
    let node = root
    for (const k of keys.slice(0, -1)) node = node[k] ??= {}
    node[keys.at(-1)] = plain(t)
  }
  return root
}

export function buildTs({ tokens }) {
  const flatPlain = Object.fromEntries([...tokens.values()].map(t => [t.path, plain(t)]))
  const vars = Object.fromEntries([...tokens.values()].map(t => [t.path, cssName(t.path)]))
  return `/* ${HEADER('Units: dimensions in px (= dp), durations in ms, colours as #rrggbb or rgba().')} */
/* eslint-disable */

export const tokens = ${JSON.stringify(nest(tokens), null, 2)} as const

/** Every token by dotted path (the same keys as tokens.flat.json). */
export const flat = ${JSON.stringify(flatPlain, null, 2)} as const

export type TokenPath = keyof typeof flat

/** Custom property name of every token, e.g. cssVarNames['color.sys.text.primary'] = '--gz-color-sys-text-primary'. */
export const cssVarNames = ${JSON.stringify(vars, null, 2)} as const satisfies Record<TokenPath, string>

/** var(--gz-...) reference for inline styles and canvas code: cssVar('space.4'). Prefer CSS classes. */
export const cssVar = (path: TokenPath): string => \`var(\${cssVarNames[path]})\`

export type Lang = 'en' | 'ar'
export type TypeRole = keyof typeof tokens.type.en
`
}

export function buildFlat({ tokens }, themes = {}) {
  const out = {}
  for (const t of tokens.values()) {
    out[t.path] = {
      type: t.type,
      value: plain(t),
      css: cssName(t.path),
      ...(t.ref ? { ref: t.ref } : {}),
      ...(t.ext?.reason ? { reason: t.ext.reason } : {}),
    }
  }
  return JSON.stringify({ $generated: 'GENERATED by packages/design-tokens/scripts/build.mjs. Do not edit.', tokens: out, ...(Object.keys(themes).length ? { themes } : {}) }, null, 2) + '\n'
}
