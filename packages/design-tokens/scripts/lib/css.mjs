// CSS generator: :root --gz-* custom properties, with the Arabic type scale under :lang(ar) (ADR 0023 D5).
import { LANGS } from './tokens.mjs'

export const HEADER = (what) => `GENERATED by packages/design-tokens/scripts/build.mjs from src/tokens.json. Do not edit (pnpm tokens).\n${what}`

/** Extra CSS names some paths also get (ADR 0024 D3 names the safe-area variables). */
const ALIASES = { 'layout.safe.top': '--gz-safe-top', 'layout.safe.bottom': '--gz-safe-bottom' }

/** path -> custom property name. font.<lang>.x -> --gz-font-x ; type.<lang>.role.prop -> --gz-type-role-prop. */
export function cssName(path) {
  const p = path.split('.')
  if (p[0] === 'font' && LANGS.includes(p[1])) return `--gz-font-${p.slice(2).join('-')}`
  if (p[0] === 'type' && LANGS.includes(p[1])) return `--gz-type-${p.slice(2).join('-')}`
  return `--gz-${p.join('-')}`
}
export const cssVar = path => `var(${cssName(path)})`

const num = n => {
  const s = String(Math.round(n * 10000) / 10000)
  return s.startsWith('0.') ? s.slice(1) : s.startsWith('-0.') ? '-' + s.slice(2) : s
}
const dim = d => (d.value === 0 ? '0' : `${num(d.value)}${d.unit}`)
const REF = /^\{([^}]+)\}$/
const refVar = s => { const m = REF.exec(s); return m ? cssVar(m[1]) : null }
const GENERIC = new Set(['serif', 'sans-serif', 'monospace', 'system-ui', 'cursive', 'fantasy'])
const family = list => list.map(f => (GENERIC.has(f) ? f : `"${f}"`)).join(', ')

export function rgba(c) {
  const [r, g, b] = c.rgb
  return c.alpha === 1 ? c.hex : `rgba(${r}, ${g}, ${b}, ${num(c.alpha)})`
}

/** One token -> CSS value string (or null when it is emitted as parts, like typography). */
export function cssValue(tok) {
  const { type, value, raw } = tok
  if (type === 'typography') return null
  if (tok.ref) return cssVar(tok.ref)
  switch (type) {
    case 'color': return rgba(value)
    case 'dimension': return dim(value)
    case 'duration': return `${value.value}${value.unit}`
    case 'cubicBezier': return `cubic-bezier(${value.map(num).join(', ')})`
    case 'number': return String(value)
    case 'fontWeight': return String(value)
    case 'fontFamily': return family(value)
    case 'string': return `"${value}"`
    case 'aspect': return `${value[0]} / ${value[1]}`
    case 'shadow':
      return raw.length === 0
        ? 'none'
        : raw.map(l => `${dim(l.offsetX)} ${dim(l.offsetY)} ${dim(l.blur)} ${dim(l.spread)} ${refVar(l.color) ?? rgba(l.color)}`).join(', ')
    case 'gradient':
      return `linear-gradient(to bottom, ${raw.map(s => `${refVar(s.color) ?? rgba(s.color)} ${num(s.position * 100)}%`).join(', ')})`
    default: throw new Error(`${tok.path}: cannot emit ${type}`)
  }
}

const typeDecls = (path, v) => {
  const base = cssName(path)
  const ff = REFfamily(v)
  return [
    [`${base}-family`, ff],
    [`${base}-size`, `${v.fontSize}px`],
    [`${base}-line`, `${v.lineHeight}px`],
    [`${base}-weight`, String(v.fontWeight)],
    [`${base}-tracking`, v.letterSpacing === 0 ? '0' : `${num(v.letterSpacing)}px`],
    [`${base}-word-spacing`, v.wordSpacing === 0 ? '0' : `${v.wordSpacing}px`],
    [`${base}-transform`, v.textTransform],
    [`${base}-numeric`, v.numeric],
  ]
}
// the typography composite keeps its fontFamily reference through `rawFamily`
function REFfamily(v) { return v.__familyVar }

const SECTIONS = [
  ['color.ref', 'Colour: reference ramps (components never read these)'],
  ['color.sys', 'Colour: semantic roles (the only colour surface for components)'],
  ['space', 'Spacing: 4-pt scale and structural aliases'],
  ['size', 'Sizes: control heights, icons, rows, knots'],
  ['radius', 'Radius'],
  ['stroke', 'Stroke'],
  ['z', 'Layers'],
  ['layout', 'Layout: device frame, safe areas, breakpoints, aspect ratios'],
  ['elevation', 'Elevation: hairline first, one warm shadow family'],
  ['shape', 'Shape'],
  ['gradient', 'Photo scrims'],
  ['motion', 'Motion: durations, easings, spring numbers, distances (ADR 0017)'],
]

export function buildCss({ tokens, flat }) {
  const lines = []
  const push = (...l) => lines.push(...l)
  const decl = (name, value) => push(`  ${name}: ${value};`)
  const by = prefix => [...tokens.values()].filter(t => t.path === prefix || t.path.startsWith(prefix + '.'))

  push(`/* ${HEADER('Light theme only (ADR 0023 D2). Every colour/space/radius/type/motion value in the product comes from here.')} */`, '')
  push(':root {')
  for (const [prefix, title] of SECTIONS) {
    push(`  /* ${title} */`)
    for (const t of by(prefix)) {
      decl(cssName(t.path), cssValue(t))
      if (ALIASES[t.path]) decl(ALIASES[t.path], cssVar(t.path))
    }
    push('')
  }
  // language-neutral families and scale constants
  push('  /* Type: shared families and derivation constants */')
  for (const t of by('font')) if (!/^font\.(en|ar)\./.test(t.path)) decl(cssName(t.path), cssValue(t))
  push('}', '')

  const langBlock = lang => {
    const out = []
    for (const t of by(`font.${lang}`)) out.push(`  ${cssName(t.path)}: ${cssValue(t)};`)
    for (const t of by(`type.${lang}`)) {
      const v = { ...t.value, __familyVar: cssVar(String(flat.get(t.path).raw.fontFamily).replace(/^\{|\}$/g, '')) }
      for (const [n, val] of typeDecls(t.path, v)) out.push(`  ${n}: ${val};`)
    }
    return out
  }
  push('/* Type scale. English is the default; Arabic runs (lang="ar") take the Arabic scale (Cairo x1.08, Amiri x1.10, explicit leading, no tracking).')
  push('   Both blocks redeclare the family variables so a nested lang switch (an Arabic name inside English UI and back) resolves correctly. */')
  push(':root,', ':lang(en) {', ...langBlock('en'), '}', '')
  push(':lang(ar) {', ...langBlock('ar'), '}', '')
  return lines.join('\n')
}
