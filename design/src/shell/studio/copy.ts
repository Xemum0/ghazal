export const COPY: Record<Lang, Record<CopyKey, string>> = { en, ar }

export function useCopy(): (key: CopyKey) => string {
  const { lang } = useLang()
  return key => COPY[lang][key]
}

/** `3 of 6` in the reading direction, with figures in the figures face by the caller's `.gz-num`. */
export const pickLoc = (loc: { en: string; ar: string }, lang: Lang): string => (lang === 'ar' ? loc.ar : loc.en)
