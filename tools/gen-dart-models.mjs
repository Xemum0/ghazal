#!/usr/bin/env node
// Generates the Dart side of the contract from packages/contracts/openapi/ghazal.v1.json (run tools/bundle-openapi.mjs first):
//
//   packages/ghazal_domain/lib/src/models/<tag>.g.dart            immutable models (const ctor, fromJson, toJson, copyWith, ==, hashCode), enums, sealed unions
//   packages/ghazal_domain/lib/src/models/models.g.dart           barrel + model registry (schema name -> fromJson, for the contract tests)
//   packages/ghazal_domain/lib/src/repositories/<tag>_repository.g.dart   one abstract interface per tag, one method per operation
//   packages/ghazal_ui/..  (nothing)   |   packages/ghazal_api/lib/src/repositories/rest_<tag>_repository.g.dart   REST implementations over GzApiClient
//
//   node tools/gen-dart-models.mjs            write
//   node tools/gen-dart-models.mjs --check    exit 1 when a committed file is stale
//
// No build_runner, freezed or json_serializable (ADR 0022 C, ADR 0036 item 3): the models are the wire models and double as entities.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const spec = JSON.parse(fs.readFileSync(path.join(root, 'packages/contracts/openapi/ghazal.v1.json'), 'utf8'))
const CHECK = process.argv.includes('--check')
const S = structuredClone(spec.components.schemas)
const HEADER = '// GENERATED by tools/gen-dart-models.mjs from packages/contracts/openapi/ghazal.v1.json. Do not edit; change the OpenAPI source and regenerate.\n// ignore_for_file: type=lint\n'

// ------------------------------------------------------------------ naming
const words = (s) => s.split(/[^A-Za-z0-9]+/).filter(Boolean).map((w) => (/^[A-Z0-9]+$/.test(w) && w.length > 1 && /[A-Z]/.test(w) ? w.toLowerCase() : w))
const pascal = (s) => words(s).map((w) => w[0].toUpperCase() + w.slice(1)).join('')
const camel = (s) => {
  const p = pascal(s)
  return p[0].toLowerCase() + p.slice(1)
}
const snake = (s) => s.replace(/-/g, '_')
const RESERVED = new Set('abstract as assert async await break case catch class const continue covariant default deferred do dynamic else enum export extends extension external factory false final finally for Function get hide if implements import in interface is late library mixin new null on operator part required rethrow return set show static super switch sync this throw true try typedef var void while with yield'.split(' '))
const safe = (n) => (RESERVED.has(n) ? `${n}_` : n)
const enumMember = (v) => {
  let n = camel(String(v))
  if (/^\d/.test(n)) n = `v${n}`
  return safe(n === 'values' || n === 'index' || n === 'name' ? `${n}_` : n)
}
const dartName = (name) => S[name]?.['x-dart-name'] ?? name
const doc = (text, indent = '') =>
  text ? String(text).trim().split('\n').map((l) => `${indent}/// ${l}`.trimEnd()).join('\n') + '\n' : ''

// ------------------------------------------------------------------ schema helpers
const isNull = (n) => n && n.type === 'null'
function unwrap(node) {
  if (!node) return { node, nullable: false }
  if (Array.isArray(node.type)) {
    const rest = node.type.filter((t) => t !== 'null')
    const nullable = rest.length !== node.type.length
    const next = { ...node, type: rest.length === 1 ? rest[0] : rest }
    if (next.enum) next.enum = next.enum.filter((v) => v !== null)
    return { node: next, nullable }
  }
  if (node.oneOf && node.oneOf.some(isNull)) {
    const rest = node.oneOf.filter((n) => !isNull(n))
    if (rest.length === 1) {
      const { description, ...siblings } = node
      delete siblings.oneOf
      return { node: { ...rest[0], ...siblings }, nullable: true }
    }
  }
  if (node.enum && node.enum.includes(null)) return { node: { ...node, enum: node.enum.filter((v) => v !== null) }, nullable: true }
  return { node, nullable: false }
}
const refName = (node) => (node.$ref ? node.$ref.replace('#/components/schemas/', '') : null)

const BUILTIN = {
  Id: 'String', Phone: 'String', IsoDate: 'LocalDate', IsoDateTime: 'DateTime', LocalTime: 'LocalTime', Money: 'MoneyAmount', LocalizedText: 'LocalizedText', Weekday: 'int',
}

/** Allow-listed oneOf unions use a discriminator; everything else is a class, enum or primitive. */
function classify(name) {
  const n = S[name]
  if (!n) throw new Error(`unknown schema ${name}`)
  if (BUILTIN[name]) return 'builtin'
  if (n['x-page-of']) return 'page'
  if (n.oneOf && n.discriminator) return 'union'
  const t = Array.isArray(n.type) ? n.type.find((x) => x !== 'null') : n.type
  if (t === 'string' && n.enum && n.enum.length > 1) return 'enum'
  if (n.allOf || n.properties || t === 'object') return 'class'
  return 'alias'
}

// ------------------------------------------------------------------ pre-pass: name inline objects and enums
function lift(parentName, propName, node, tag, isItem = false) {
  if (!node || node.$ref) return node
  const { node: inner, nullable } = unwrap(node)
  const wrapBack = (n) => (nullable ? { oneOf: [n, { type: 'null' }] } : n)
  if (inner.type === 'array' && inner.items) {
    return wrapBack({ ...inner, items: lift(parentName, propName, inner.items, tag, true) })
  }
  if (inner.type === 'string' && inner.enum && inner.enum.length > 1) {
    const name = `${parentName}${pascal(propName)}`
    if (!S[name]) S[name] = { type: 'string', enum: inner.enum, description: inner.description, 'x-tag': tag }
    return wrapBack({ $ref: `#/components/schemas/${name}` })
  }
  if (inner.type === 'object' && inner.properties) {
    const name = `${parentName}${pascal(propName)}${isItem ? 'Item' : ''}`
    S[name] = { ...inner, 'x-tag': tag }
    liftProperties(name)
    return wrapBack({ $ref: `#/components/schemas/${name}` })
  }
  return node
}
function liftProperties(name) {
  const n = S[name]
  const tag = n['x-tag']
  if (n.properties) for (const [k, v] of Object.entries(n.properties)) n.properties[k] = lift(name, k, v, tag)
  if (n.allOf) n.allOf = n.allOf.map((m, i) => (m.properties ? (() => { const holder = { properties: { ...m.properties } }; for (const [k, v] of Object.entries(holder.properties)) holder.properties[k] = lift(name, k, v, tag); return { ...m, properties: holder.properties } })() : m))
}
for (const name of Object.keys(S)) liftProperties(name)

/** All properties of a class schema, with allOf flattened. */
function flat(nameOrNode) {
  const n = typeof nameOrNode === 'string' ? S[nameOrNode] : nameOrNode
  const props = new Map()
  const required = new Set()
  const add = (node) => {
    if (node.$ref) { const f = flat(refName(node)); for (const [k, v] of f.props) props.set(k, v); for (const r of f.required) required.add(r); return }
    if (node.allOf) node.allOf.forEach(add)
    for (const [k, v] of Object.entries(node.properties ?? {})) props.set(k, v)
    for (const r of node.required ?? []) required.add(r)
  }
  if (n.allOf) n.allOf.forEach(add)
  for (const [k, v] of Object.entries(n.properties ?? {})) props.set(k, v)
  for (const r of n.required ?? []) required.add(r)
  return { props, required }
}

// ------------------------------------------------------------------ type resolution
let depth = 0
const lv = () => `v${++depth}`

/** info: { dart, parse(expr), ser(expr), deep } for a non-null type. */
function typeOf(rawNode) {
  const { node } = unwrap(rawNode)
  if (node.$ref || (node.allOf && node.allOf.length === 1 && node.allOf[0].$ref)) {
    const name = refName(node.$ref ? node : node.allOf[0])
    return refInfo(name)
  }
  const t = Array.isArray(node.type) ? node.type.find((x) => x !== 'null') : node.type
  switch (t) {
    case 'string':
      if (node.enum && node.enum.length === 1) return prim('String', 'asString', null)
      if (node.format === 'date-time') return { dart: 'DateTime', parse: (e) => `asInstant(${e})`, ser: (e) => `instantToJson(${e})`, deep: false }
      if (node.format === 'date') return { dart: 'LocalDate', parse: (e) => `asLocalDate(${e})`, ser: (e) => `${e}.toJson()`, deep: false }
      if (node.format === 'local-time') return { dart: 'LocalTime', parse: (e) => `asLocalTime(${e})`, ser: (e) => `${e}.toJson()`, deep: false }
      if (node.format === 'binary') return { dart: 'List<int>', parse: (e) => `(${e} as List).cast<int>()`, ser: (e) => e, deep: true }
      return prim('String', 'asString')
    case 'integer': return prim('int', 'asInt')
    case 'number': return prim('double', 'asDouble')
    case 'boolean': return prim('bool', 'asBool')
    case 'array': {
      const { node: itemNode, nullable } = unwrap(node.items)
      const el = typeOf(itemNode)
      const dartEl = nullable ? `${el.dart}?` : el.dart
      return {
        dart: `List<${dartEl}>`,
        parse: (e) => { const v = lv(); const inner = nullable ? `nullable(${v}, (${v}n) => ${el.parse(`${v}n`)})` : el.parse(v); return `asList(${e}, (${v}) => ${inner})` },
        ser: (e) => (el.ser('x') === 'x' && !nullable ? e : (() => { const v = lv(); const s = el.ser(v); return `${e}.map((${v}) => ${nullable ? `${v} == null ? null : ${el.ser(v)}` : s}).toList()` })()),
        deep: true,
      }
    }
    case 'object': {
      const ap = node.additionalProperties
      if (ap && typeof ap === 'object') {
        const el = typeOf(ap)
        return {
          dart: `Map<String, ${el.dart}>`,
          parse: (e) => { const v = lv(); const inner = el.parse(v); return `asStringMap(${e}, (${v}) => ${inner})` },
          ser: (e) => (el.ser('x') === 'x' ? e : (() => { const v = lv(); const s = el.ser(v); return `${e}.map((k, ${v}) => MapEntry(k, ${s}))` })()),
          deep: true,
        }
      }
      return { dart: 'Map<String, Object?>', parse: (e) => `asMap(${e})`, ser: (e) => e, deep: true }
    }
    default:
      if (!t) return { dart: 'Object?', parse: (e) => `asAny(${e})`, ser: (e) => e, deep: true }
      throw new Error(`unsupported schema type ${JSON.stringify(node).slice(0, 120)}`)
  }
}
const prim = (dart, fn) => ({ dart, parse: (e) => `${fn}(${e})`, ser: (e) => e, deep: false })

function refInfo(name) {
  const kind = classify(name)
  const d = dartName(name)
  switch (kind) {
    case 'builtin': {
      const dart = BUILTIN[name]
      if (dart === 'String') return prim('String', 'asString')
      if (dart === 'int') return prim('int', 'asInt')
      if (dart === 'DateTime') return { dart, parse: (e) => `asInstant(${e})`, ser: (e) => `instantToJson(${e})`, deep: false }
      if (dart === 'LocalDate') return { dart, parse: (e) => `asLocalDate(${e})`, ser: (e) => `${e}.toJson()`, deep: false }
      if (dart === 'LocalTime') return { dart, parse: (e) => `asLocalTime(${e})`, ser: (e) => `${e}.toJson()`, deep: false }
      return { dart, parse: (e) => `${dart}.fromJson(asMap(${e}))`, ser: (e) => `${e}.toJson()`, deep: false }
    }
    case 'enum': return { dart: d, parse: (e) => `${d}.fromJson(${e})`, ser: (e) => `${e}.toJson()`, deep: false, isEnum: true }
    case 'class':
    case 'union': return { dart: d, parse: (e) => `${d}.fromJson(asMap(${e}))`, ser: (e) => `${e}.toJson()`, deep: false }
    case 'alias': return typeOf({ ...S[name], $ref: undefined })
    case 'page': throw new Error(`page schema ${name} used as a property`)
    default: throw new Error(`cannot resolve ${name}`)
  }
}

// ------------------------------------------------------------------ emitters: enums, classes, unions
function emitEnum(name) {
  const n = S[name]
  const vals = n.enum.filter((v) => v !== null)
  const members = vals.map((v) => ({ id: enumMember(v), raw: v }))
  if (!members.some((m) => m.raw === 'unknown')) members.push({ id: 'unknown', raw: 'unknown' })
  const d = dartName(name)
  return `${doc(n.description)}enum ${d} {
${members.map((m, i) => `  ${m.id}('${m.raw}')${i === members.length - 1 ? ';' : ','}`).join('\n')}

  const ${d}(this.value);

  /// The wire value.
  final String value;

  /// Unknown values never crash a client: they read as [unknown] (api-conventions section 2).
  static ${d} fromJson(Object? v) {
    for (final e in values) {
      if (e.value == v) return e;
    }
    return ${d}.unknown;
  }

  String toJson() => value;
}
`
}

/** variant class name -> { union, prop, value } */
const variantOf = new Map()
for (const name of Object.keys(S)) {
  if (S[name].oneOf && S[name].discriminator) {
    const { propertyName, mapping } = S[name].discriminator
    for (const [value, ref] of Object.entries(mapping)) variantOf.set(refName({ $ref: ref }), { union: name, prop: propertyName, value })
  }
}

function fieldsOf(name) {
  const { props, required } = flat(name)
  const variant = variantOf.get(name)
  const out = []
  for (const [key, rawNode] of props) {
    if (variant && key === variant.prop) continue
    const { node, nullable } = unwrap(rawNode)
    const info = typeOf(node)
    const isRequired = required.has(key)
    const optional = !isRequired
    out.push({
      key, field: safe(camel(key) === 'hashCode' ? 'hashCode_' : camel(key)), info, nullable: nullable || optional, required: isRequired, omitIfNull: optional,
      description: rawNode.description ?? node.description, type: info.dart + (nullable || optional ? '?' : ''),
    })
  }
  return out
}

function nullSer(f, expr = f.field) {
  return f.nullable ? `${expr} == null ? null : ${f.info.ser(`${expr}!`)}` : f.info.ser(expr)
}

function emitClass(name, unionBase) {
  const n = S[name]
  const d = dartName(name)
  const fields = fieldsOf(name)
  const variant = variantOf.get(name)
  const common = unionBase ? unionBase.commonNames : new Set()
  const sig = fields.map((f) => `    ${f.required && !f.nullable ? 'required ' : f.required ? 'required ' : ''}this.${f.field},`).join('\n')
  const decl = fields.map((f) => `${doc(f.description, '  ')}${common.has(f.field) ? '  @override\n' : ''}  final ${f.type} ${f.field};`).join('\n')
  const parse = fields
    .map((f) => {
      depth = 0
      const body = f.info.parse('v')
      return `        ${f.field}: ${f.nullable ? `optField(json, '${f.key}', (v) => ${body})` : `reqField(json, '${f.key}', (v) => ${body})`},`
    })
    .join('\n')
  const ser = fields
    .map((f) => {
      depth = 0
      return f.omitIfNull ? `      if (${f.field} != null) '${f.key}': ${f.info.ser(`${f.field}!`)},` : `      '${f.key}': ${nullSer(f)},`
    })
    .join('\n')
  const copyParams = fields.map((f) => (f.nullable ? `    Object? ${f.field} = unsetValue,` : `    ${f.info.dart}? ${f.field},`)).join('\n')
  const copyArgs = fields
    .map((f) => (f.nullable ? `      ${f.field}: identical(${f.field}, unsetValue) ? this.${f.field} : ${f.field} as ${f.type},` : `      ${f.field}: ${f.field} ?? this.${f.field},`))
    .join('\n')
  const eq = fields.map((f) => (f.info.deep ? `deepEquals(other.${f.field}, ${f.field})` : `other.${f.field} == ${f.field}`))
  const hash = fields.map((f) => (f.info.deep ? `deepHash(${f.field})` : f.field))
  const ext = unionBase ? ` extends ${unionBase.dart}` : ''
  const discGetter = variant ? `\n  @override\n  String get ${safe(camel(variant.prop))} => '${variant.value}';\n` : ''
  const discSer = variant ? `      '${variant.prop}': '${variant.value}',\n` : ''
  return `${doc(n.description)}final class ${d}${ext} {
  const ${d}(${fields.length ? `{\n${sig}\n  }` : ''});

  factory ${d}.fromJson(Map<String, Object?> json) {
    try {
      return ${d}(
${parse}
      );
    } on FormatException catch (e) {
      throw FormatException('${d}: \${e.message}');
    }
  }

${decl}
${discGetter}
${unionBase ? '  @override\n' : ''}  Map<String, Object?> toJson() => {
${discSer}${ser}
      };

  ${d} copyWith(${fields.length ? `{\n${copyParams}\n  }` : ''}) => ${d}(
${copyArgs}
      );

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      other is ${d}${eq.length ? ` &&\n          ${eq.join(' &&\n          ')}` : ''};

  @override
  int get hashCode => ${hash.length ? `Object.hashAll([${hash.join(', ')}])` : `${d}.hashCode`};

  @override
  String toString() => '${d}(\${toJson()})';
}
`.replace(`${d}.hashCode`, `0`)
}

function emitUnion(name) {
  const n = S[name]
  const d = dartName(name)
  const { propertyName, mapping } = n.discriminator
  const variants = Object.entries(mapping).map(([value, ref]) => ({ value, name: refName({ $ref: ref }) }))
  // properties common to every variant with the same Dart type become abstract getters on the base
  const lists = variants.map((v) => new Map(fieldsOf(v.name).map((f) => [f.field, f])))
  const commonNames = new Set([...lists[0].keys()].filter((k) => lists.every((m) => m.has(k) && m.get(k).type === lists[0].get(k).type)))
  const getters = [...commonNames].map((k) => `  ${lists[0].get(k).type} get ${k};`).join('\n')
  const cases = variants.map((v) => `      case '${v.value}':\n        return ${dartName(v.name)}.fromJson(json);`).join('\n')
  const base = `${doc(n.description)}sealed class ${d} {
  const ${d}();

  factory ${d}.fromJson(Map<String, Object?> json) {
    final tag = json['${propertyName}'];
    switch (tag) {
${cases}
      default:
        throw FormatException('${d}: unknown ${propertyName} \$tag');
    }
  }

  /// The discriminator (\`${propertyName}\`).
  String get ${safe(camel(propertyName))};

${getters}

  Map<String, Object?> toJson();
}
`
  const classes = variants.map((v) => emitClass(v.name, { dart: d, commonNames }))
  return [base, ...classes].join('\n')
}

// ------------------------------------------------------------------ models per tag
const byTag = new Map()
const unionVariants = new Set([...variantOf.keys()])
for (const name of Object.keys(S)) {
  const kind = classify(name)
  if (kind === 'builtin' || kind === 'page' || kind === 'alias' || S[name]['x-abstract']) continue
  if (S[name].type === 'string' && !S[name].enum) continue
  if (!byTag.has(S[name]['x-tag'])) byTag.set(S[name]['x-tag'], [])
  byTag.get(S[name]['x-tag']).push(name)
}
const modelTag = new Map()
for (const [tag, names] of byTag) for (const nm of names) modelTag.set(nm, tag)
for (const [vn, v] of variantOf) { void vn; void v }

const fileOf = (tag) => snake(tag)
function emitModelsFile(tag, names) {
  const body = []
  const deps = new Set()
  for (const nm of names) {
    const kind = classify(nm)
    if (kind === 'enum') body.push(emitEnum(nm))
    else if (kind === 'union') body.push(emitUnion(nm))
    else if (kind === 'class' && !unionVariants.has(nm)) body.push(emitClass(nm))
    if (kind === 'union') for (const v of Object.values(S[nm].discriminator.mapping)) { void v }
  }
  const text = body.join('\n')
  // variants are emitted with their union; make sure their own tag file does not emit them twice (handled by the unionVariants check)
  for (const other of byTag.keys()) if (other !== tag && new RegExp(`\\b(${byTag.get(other).map(dartName).join('|')})\\b`).test(text)) deps.add(other)
  const imports = [`import '../core/core.dart';`, ...[...deps].sort().map((t) => `import '${fileOf(t)}.g.dart';`)]
  return `${HEADER}\n${imports.join('\n')}\n\n${text}`
}

// union variants whose own tag differs from the union's tag must still be emitted exactly once: emit them with the union
for (const [vn, v] of variantOf) {
  const ut = S[v.union]['x-tag']
  const vt = S[vn]['x-tag']
  if (ut !== vt) throw new Error(`union ${v.union} (${ut}) and variant ${vn} (${vt}) must live in the same tag file`)
}

// ------------------------------------------------------------------ operations
const OPS = []
for (const [p, item] of Object.entries(spec.paths)) {
  for (const [method, op] of Object.entries(item)) OPS.push({ path: p, method: method.toUpperCase(), op })
}
const resolveParam = (p) => (p.$ref ? spec.components.parameters[p.$ref.split('/').pop()] : p)
function describeOp({ path: p, method, op }) {
  const params = (op.parameters ?? []).map(resolveParam)
  const pathParams = params.filter((x) => x.in === 'path')
  const queryParams = params.filter((x) => x.in === 'query' && !['cursor', 'limit'].includes(x.name))
  const paged = params.some((x) => x.in === 'query' && x.name === 'cursor')
  const idem = params.some((x) => x.name === 'Idempotency-Key')
  const ifMatch = params.some((x) => x.name === 'If-Match')
  const bodyRef = op.requestBody?.content?.['application/json']?.schema
  const okCode = Object.keys(op.responses).find((c) => c.startsWith('2'))
  const ok = op.responses[okCode]
  let result = { kind: 'void' }
  const content = ok.content
  if (content?.['application/pdf']) result = { kind: 'bytes' }
  else if (content?.['application/json']) {
    const sch = content['application/json'].schema
    if (sch.type === 'array') {
      const el = typeOf(sch.items)
      result = { kind: 'list', el }
    } else {
      const nm = refName(sch)
      if (S[nm]?.['x-page-of']) result = { kind: 'page', el: refInfo(S[nm]['x-page-of']) }
      else result = { kind: 'one', info: refInfo(nm) }
    }
  }
  return { path: p, method, op, pathParams, queryParams, paged, idem, ifMatch, bodyRef, result, tag: op.tags[0] }
}
const DESCRIBED = OPS.map(describeOp)
const byOpTag = new Map()
for (const d of DESCRIBED) {
  if (!byOpTag.has(d.tag)) byOpTag.set(d.tag, [])
  byOpTag.get(d.tag).push(d)
}

function paramDecl(d) {
  const parts = []
  for (const p of d.pathParams) parts.push({ name: safe(camel(p.name)), type: typeOf(p.schema).dart, required: true })
  for (const q of d.queryParams) {
    const { nullable } = unwrap(q.schema)
    void nullable
    const info = typeOf(q.schema)
    parts.push({ name: safe(camel(q.name)), type: info.dart, required: !!q.required, q, info })
  }
  if (d.paged) parts.push({ name: 'cursor', type: 'String', required: false }, { name: 'limit', type: 'int', required: false })
  if (d.bodyRef) parts.push({ name: 'body', type: typeOf(d.bodyRef).dart, required: true })
  if (d.ifMatch) parts.push({ name: 'ifMatch', type: 'String', required: true })
  if (d.idem) parts.push({ name: 'idempotencyKey', type: 'String', required: false })
  return parts
}
const sigOf = (parts) => (parts.length ? `({\n${parts.map((p) => `    ${p.required ? 'required ' : ''}${p.type}${p.required ? '' : '?'} ${p.name},`).join('\n')}\n  })` : '()')
const returnType = (r) => {
  switch (r.kind) {
    case 'void': return 'Future<void>'
    case 'bytes': return 'Future<List<int>>'
    case 'list': return `Future<List<${r.el.dart}>>`
    case 'page': return `Future<Page<${r.el.dart}>>`
    default: return `Future<${r.info.dart}>`
  }
}
const errorsNote = (op) => (op['x-errors']?.length ? `Errors (problem+json \`code\`): ${op['x-errors'].join(', ')}.` : '')
const rolesNote = (op) => `Access: ${op['x-access'] === 'bearer' ? 'signed in' : op['x-access']}${op['x-roles']?.length ? `; roles: ${op['x-roles'].join(', ')}` : ''}${op['x-permissions']?.length ? `; permissions: ${op['x-permissions'].join(', ')}` : ''}.`

function repoName(tag) { return `${pascal(tag)}Repository` }

function emitInterface(tag, ops) {
  const methods = ops.map((d) => {
    const parts = paramDecl(d)
    const lines = [d.op.summary, '', d.op.description, `\`${d.method} ${d.path}\``, rolesNote(d.op), errorsNote(d.op), d.idem ? 'Pass the same [idempotencyKey] when the user retries the same intent; a fresh one is generated when null.' : '', d.ifMatch ? 'Send the `ETag` of the document being changed, for example `versionTag(booking.version)`.' : ''].filter((x, i) => x || i === 1)
    return `${doc(lines.join('\n').replace(/\n\n\n/g, '\n\n'), '  ')}  ${returnType(d.result)} ${d.op.operationId}${sigOf(parts)};`
  })
  const tagDesc = spec.tags.find((t) => t.name === tag)?.description ?? ''
  return `${HEADER}\nimport '../core/core.dart';\nimport '../models/models.g.dart';\n\n${doc(`${tagDesc}\n\nOne method per operation of the \`${tag}\` tag of the contract (the server owns every rule; this surface only carries data).`)}abstract interface class ${repoName(tag)} {\n${methods.join('\n\n')}\n}\n`
}

function qExpr(p) {
  const nullable = !p.required
  const e = p.name
  const s = p.info.ser(nullable ? e : e)
  if (!nullable) return s
  return `${e} == null ? null : ${p.info.ser(e)}`
}

function emitRest(tag, ops) {
  const cls = `Rest${repoName(tag)}`
  const methods = ops.map((d) => {
    const parts = paramDecl(d)
    let urlPath = d.path.replace(/\{(\w+)\}/g, (_, n) => {
      const p = d.pathParams.find((x) => x.name === n)
      const info = typeOf(p.schema)
      depth = 0
      return `\${Uri.encodeComponent(${info.ser(safe(camel(n)))}${info.dart === 'String' ? '' : ''})}`
    })
    const args = [`'${d.method}'`, `'${urlPath}'`]
    const named = []
    if (d.queryParams.length || d.paged) {
      const q = d.queryParams.map((x) => { depth = 0; return `        '${x.name}': ${qExpr({ name: safe(camel(x.name)), required: !!x.required, info: typeOf(x.schema) })},` })
      if (d.paged) q.push(`        'cursor': cursor,`, `        'limit': limit,`)
      named.push(`query: {\n${q.join('\n')}\n      }`)
    }
    if (d.bodyRef) named.push('body: body.toJson()')
    if (d.idem) named.push('idempotent: true', 'idempotencyKey: idempotencyKey')
    if (d.ifMatch) named.push('ifMatch: ifMatch')
    const call = (fn) => `_client.${fn}(${[...args, ...named].join(', ')})`
    let body
    depth = 0
    switch (d.result.kind) {
      case 'void': body = `    await ${call('send')};`; break
      case 'bytes': body = `    return ${call('sendBytes')};`; break
      case 'list': body = `    final json = await ${call('send')};\n    return asList(json, (v) => ${d.result.el.parse('v')});`; break
      case 'page': body = `    final json = await ${call('send')};\n    return Page.fromJson(asMap(json), (v) => ${d.result.el.parse('v')});`; break
      default: body = `    final json = await ${call('send')};\n    return ${d.result.info.parse('json')};`
    }
    return `  @override\n  ${returnType(d.result)} ${d.op.operationId}${sigOf(parts)} async {\n${body}\n  }`
  })
  return `${HEADER}\nimport 'package:ghazal_domain/ghazal_domain.dart';\n\nimport '../client/gz_api_client.dart';\n\n/// REST implementation of [${repoName(tag)}] over [GzApiClient].\nfinal class ${cls} implements ${repoName(tag)} {\n  const ${cls}(this._client);\n\n  final GzApiClient _client;\n\n${methods.join('\n\n')}\n}\n`
}

