#!/usr/bin/env node
// Icon font generator (ADR 0036 item 5): packages/design-tokens/icons/regular/*.svg (+ brand glyphs) -> a TTF and its Dart registry.
//   node tools/gen-icons.mjs            write packages/ghazal_ui/assets/fonts/GzIcons.ttf, GzIcons.codepoints.json, lib/src/icons/gz_icons.g.dart
//   node tools/gen-icons.mjs --check    fail when the Dart registry or the codepoint map is stale (does not rebuild the font)
// Font tool: fantasticon (npx, pinned below). Glyphs are the product weight (Phosphor Regular, strokes outlined into fills, viewBox 256, the weight the
// web Icon renders: icons/manifest.json defaultWeight). Every glyph is scaled by the same factor (em = 256 units), so sizes match the web exactly.
// Codepoints are stable: an existing name keeps its codepoint (GzIcons.codepoints.json is committed), new names take the next free one.
import { execFileSync } from 'node:child_process'
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const FANTASTICON = 'fantasticon@4.1.0'
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const tokens = join(root, 'packages/design-tokens')
const ui = join(root, 'packages/ghazal_ui')
const ttfOut = join(ui, 'assets/fonts/GzIcons.ttf')
const mapOut = join(ui, 'assets/fonts/GzIcons.codepoints.json')
const dartOut = join(ui, 'lib/src/icons/gz_icons.g.dart')
const check = process.argv.includes('--check')

const manifest = JSON.parse(readFileSync(join(tokens, 'icons/manifest.json'), 'utf8'))
const entries = { ...manifest.icons, ...manifest.fills }
const names = Object.keys(entries)
const mirrored = new Set(names.filter(n => entries[n].mirror))
const read = f => readFileSync(f, 'utf8')
const pathsOf = svg => [...svg.matchAll(/<path\b[^>]*\bd="([^"]+)"/g)].map(m => m[1])

// Glyph sources: name -> svg text. Brand marks are re-boxed so the em square stays 1:1 with the font size.
const glyphs = {}
for (const n of names) glyphs[n] = read(join(tokens, `icons/regular/${n}.svg`))
const KNOT = 'M4 0L8 4L4 8L0 4Z'
const DIV = ['M0 3.5H48V4.5H0Z', 'M52 0L56 4L52 8L48 4Z']
const brand = { knot: read(join(tokens, 'icons/brand/knot.svg')), divider: read(join(tokens, 'icons/brand/divider.svg')) }
if (pathsOf(brand.knot).join() !== KNOT || pathsOf(brand.divider).join() !== DIV.join()) {
  console.error('gen-icons: icons/brand/*.svg changed; update the re-boxed brand glyph paths in tools/gen-icons.mjs')
  process.exit(1)
}
// Re-box a brand glyph onto the font's 256 unit em (the font tool scales every glyph by one factor, 1024 / 256 = 4 font units per unit of
// a 256 viewBox, so a small viewBox would come out tiny). Absolute M L H V Z paths only. knot: its own 8 x 8 box (square: use at size 8).
// divider: the 56 x 8 line centred vertically in a 56 x 56 box (use at size 56, so its length is the web 56).
const rebox = (d, k, dy = 0) => d.replace(/([MLHV])([^MLHVZ]*)/g, (_, cmd, args) => {
  const v = args.trim().split(/[\s,]+/).filter(Boolean).map(Number)
  const f = x => +(x * k).toFixed(3)
  if (cmd === 'H') return `H${f(v[0])}`
  if (cmd === 'V') return `V${f(v[0] + dy)}`
  return cmd + v.map((x, i) => (i % 2 ? f(x + dy) : f(x))).join(' ')
}).replace(/Z/g, 'Z')
const em = (paths) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256">${paths.map(d => `<path d="${d}"/>`).join('')}</svg>`
glyphs.brandKnot = em([rebox(KNOT, 256 / 8)])
glyphs.brandDivider = em(DIV.map(d => rebox(d, 256 / 56, 24)))
mirrored.add('brandDivider')
const all = Object.keys(glyphs)

// Stable codepoints (Private Use Area from U+E000).
const prior = existsSync(mapOut) ? JSON.parse(read(mapOut)) : {}
const codepoints = { ...prior }
let next = Math.max(0xe000 - 1, ...Object.values(prior)) + 1
for (const n of all) if (!(n in codepoints)) codepoints[n] = next++
const sorted = Object.fromEntries(Object.entries(codepoints).filter(([n]) => n in glyphs).sort((a, b) => a[1] - b[1]))
const mapText = JSON.stringify(sorted, null, 1) + '\n'

const camel = n => n.split('-').map((p, i) => (i ? p[0].toUpperCase() + p.slice(1) : p)).join('')
const dart = `// GENERATED by tools/gen-icons.mjs from packages/design-tokens/icons (Phosphor Regular, MIT, plus the brand glyphs). Do not edit (pnpm flutter:icons).
// ignore_for_file: lines_longer_than_80_chars
import 'package:flutter/widgets.dart' show IconData;

/// The icon font (assets/fonts/GzIcons.ttf, family GzIcons): ${all.length} glyphs, one em = the 24 dp grid at size 24.
/// Directional glyphs (ADR 0014) carry matchTextDirection, so they flip in RTL even through a plain Icon.
abstract final class GzIcons {
  static const String fontFamilyName = 'GzIcons';
  static const String fontPackageName = 'ghazal_ui';

${all.map(n => `  static const IconData ${camel(n)} = IconData(0x${sorted[n].toString(16)}, fontFamily: fontFamilyName, fontPackage: fontPackageName${mirrored.has(n) ? ', matchTextDirection: true' : ''});`).join('\n')}

  /// Registry by product (web) name, for example \`GzIcons.byName['heart-fill']\`. Brand glyphs are \`brand-knot\` (use at size 8) and \`brand-divider\` (size 56).
  static const Map<String, IconData> byName = {
${all.map(n => `    '${n.replace(/[A-Z]/g, c => '-' + c.toLowerCase())}': ${camel(n)},`).join('\n')}
  };

  /// Names whose glyph flips in right-to-left layouts (ADR 0014 D2; the icons manifest mirror flag).
  static const Set<String> mirrorInRtl = {
${[...mirrored].map(n => `    '${n.replace(/[A-Z]/g, c => '-' + c.toLowerCase())}',`).join('\n')}
  };
}
`

if (check) {
  const stale = []
  if (!existsSync(dartOut) || read(dartOut) !== dart) stale.push(dartOut)
  if (!existsSync(mapOut) || read(mapOut) !== mapText) stale.push(mapOut)
  if (!existsSync(ttfOut)) stale.push(ttfOut)
  if (stale.length) {
    console.error(`gen-icons --check: stale ${stale.join(', ')}. Run pnpm flutter:icons.`)
    process.exit(1)
  }
  console.log(`gen-icons --check ok: ${all.length} glyphs`)
  process.exit(0)
}

const work = mkdtempSync(join(tmpdir(), 'gzicons-'))
mkdirSync(join(work, 'in'))
mkdirSync(join(work, 'out'))
for (const n of all) writeFileSync(join(work, 'in', `${n}.svg`), glyphs[n])
const rc = { inputDir: join(work, 'in'), outputDir: join(work, 'out'), name: 'GzIcons', fontTypes: ['ttf'], assetTypes: [], normalize: false, fontHeight: 1024, descent: 0, codepoints: sorted, prefix: 'gz' }
writeFileSync(join(work, 'rc.json'), JSON.stringify(rc))
execFileSync('npx', ['--yes', FANTASTICON, '--config', join(work, 'rc.json')], { stdio: 'inherit' })
mkdirSync(dirname(ttfOut), { recursive: true })
mkdirSync(dirname(dartOut), { recursive: true })
copyFileSync(join(work, 'out/GzIcons.ttf'), ttfOut)
writeFileSync(mapOut, mapText)
writeFileSync(dartOut, dart)
console.log(`gen-icons: ${all.length} glyphs -> ${ttfOut}, ${dartOut}`)
